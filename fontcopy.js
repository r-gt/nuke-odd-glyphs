function clone_glyphs(){

	const buffer = document.getElementById('font_file').files[0].arrayBuffer();

	buffer.then(data => {

			font = opentype.parse(data);

			for (const ch of new Set(text)) {

				const base = ch.normalize("NFKD")[0];
				const target = font.charToGlyph(base);

				if (base === ch || target.index === 0) continue;


				const cp = ch.codePointAt(0);
				const existing = font.charToGlyph(ch);


				if (existing.index !== 0) {

					existing.path = target.path;
					existing.advanceWidth = target.advanceWidth;

				} else {

					font.glyphs.push(font.glyphs.length, new opentype.Glyph({

						name: "u" + cp.toString(16),
										unicode: cp,
										advanceWidth: target.advanceWidth,
										path: target.path
					}));

				}

			}

			const blob = new Blob([font.toArrayBuffer()], { type: "font/ttf" });

			const link = document.createElement('a');
			link.href = URL.createObjectURL(blob);
			link.download = 'modified-font.ttf';
			link.click();

	})
}
